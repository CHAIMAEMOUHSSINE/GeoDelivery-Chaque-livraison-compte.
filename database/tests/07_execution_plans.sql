-- Comparer le meme filtre de rayon, pas SDO_NN sans index (operateur dependant d'un index).
EXPLAIN PLAN SET STATEMENT_ID='GD_INDEX' FOR
SELECT d.id FROM DRIVER d WHERE SDO_WITHIN_DISTANCE(d.current_position,
 MDSYS.SDO_GEOMETRY(2001,4326,MDSYS.SDO_POINT_TYPE(-7.63,33.53,NULL),NULL,NULL),
 'distance=5 unit=KM')='TRUE';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY(NULL,'GD_INDEX','TYPICAL'));
EXPLAIN PLAN SET STATEMENT_ID='GD_SCAN' FOR
SELECT d.id FROM DRIVER d WHERE SDO_GEOM.SDO_DISTANCE(d.current_position,
 MDSYS.SDO_GEOMETRY(2001,4326,MDSYS.SDO_POINT_TYPE(-7.63,33.53,NULL),NULL,NULL),
 0.005,'unit=KM')<=5;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY(NULL,'GD_SCAN','TYPICAL'));
