-- Jeu independant des livreurs metier. Creation unique, sans DROP.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE GD_BENCH_POINT (id NUMBER PRIMARY KEY, position MDSYS.SDO_GEOMETRY NOT NULL);
INSERT INTO GD_BENCH_POINT
SELECT LEVEL,MDSYS.SDO_GEOMETRY(2001,4326,MDSYS.SDO_POINT_TYPE(
 -7.9+MOD(LEVEL*17,1000)*0.0006,33.3+MOD(LEVEL*31,997)*0.0006,NULL),NULL,NULL)
FROM dual CONNECT BY LEVEL<=20000;
INSERT INTO USER_SDO_GEOM_METADATA(TABLE_NAME,COLUMN_NAME,DIMINFO,SRID)
VALUES('GD_BENCH_POINT','POSITION',MDSYS.SDO_DIM_ARRAY(
 MDSYS.SDO_DIM_ELEMENT('Longitude',-180,180,0.005),
 MDSYS.SDO_DIM_ELEMENT('Latitude',-90,90,0.005)),4326);
COMMIT;
CREATE INDEX idx_gd_bench_position ON GD_BENCH_POINT(position) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER,'GD_BENCH_POINT'); END;
