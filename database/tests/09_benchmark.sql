SET PAGESIZE 1000 LINESIZE 200
-- Meme jeu de 20 000 points, meme centre, rayon=5 km, distance geodesique.
-- 2 echauffements, puis 10 repetitions alternees. Chronometre resolution 10 ms.
DECLARE
 p MDSYS.SDO_GEOMETRY:=MDSYS.SDO_GEOMETRY(2001,4326,MDSYS.SDO_POINT_TYPE(-7.63,33.57,NULL),NULL,NULL);
 n_index NUMBER; n_scan NUMBER; t NUMBER; indexed_ms NUMBER; scan_ms NUMBER;
BEGIN
 FOR i IN 1..12 LOOP
  t:=DBMS_UTILITY.GET_TIME;
  SELECT COUNT(*) INTO n_index FROM GD_BENCH_POINT b WHERE SDO_WITHIN_DISTANCE(b.position,p,'distance=5 unit=KM')='TRUE';
  indexed_ms:=(DBMS_UTILITY.GET_TIME-t)*10;
  t:=DBMS_UTILITY.GET_TIME;
  SELECT COUNT(*) INTO n_scan FROM GD_BENCH_POINT b WHERE SDO_GEOM.SDO_DISTANCE(b.position,p,0.005,'unit=KM')<=5;
  scan_ms:=(DBMS_UTILITY.GET_TIME-t)*10;
  IF n_index<>n_scan THEN RAISE_APPLICATION_ERROR(-20010,'Resultats differents : comparer les tolerances'); END IF;
  IF i>2 THEN DBMS_OUTPUT.PUT_LINE('BENCH,'||(i-2)||','||n_index||','||indexed_ms||','||scan_ms); END IF;
 END LOOP;
END;
/
EXPLAIN PLAN SET STATEMENT_ID='GD_BENCH_INDEX' FOR
 SELECT b.id FROM GD_BENCH_POINT b WHERE SDO_WITHIN_DISTANCE(b.position,
 MDSYS.SDO_GEOMETRY(2001,4326,MDSYS.SDO_POINT_TYPE(-7.63,33.57,NULL),NULL,NULL),'distance=5 unit=KM')='TRUE';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY(NULL,'GD_BENCH_INDEX','TYPICAL'));
EXPLAIN PLAN SET STATEMENT_ID='GD_BENCH_SCAN' FOR
 SELECT b.id FROM GD_BENCH_POINT b WHERE SDO_GEOM.SDO_DISTANCE(b.position,
 MDSYS.SDO_GEOMETRY(2001,4326,MDSYS.SDO_POINT_TYPE(-7.63,33.57,NULL),NULL,NULL),0.005,'unit=KM')<=5;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY(NULL,'GD_BENCH_SCAN','TYPICAL'));
