-- DBA uniquement, dans ORCLPDB (pas CDB$ROOT). A executer une seule fois.
-- SQL Developer : definir GD_PASSWORD avec une valeur forte quand demande.
WHENEVER SQLERROR EXIT SQL.SQLCODE
ACCEPT GD_PASSWORD CHAR PROMPT 'Mot de passe du nouveau schema GEODELIVERY : ' HIDE
CREATE USER GEODELIVERY IDENTIFIED BY "&GD_PASSWORD" DEFAULT TABLESPACE USERS QUOTA 200M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER TO GEODELIVERY;
-- Oracle 19c : permettre aux packages invoker-rights Spatial d'utiliser ce seul utilisateur.
GRANT INHERIT PRIVILEGES ON USER GEODELIVERY TO MDSYS;
UNDEFINE GD_PASSWORD
