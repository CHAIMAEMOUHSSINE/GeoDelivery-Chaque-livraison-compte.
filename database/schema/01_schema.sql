CREATE TABLE APP_USER (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR2(180) NOT NULL UNIQUE,
 password_hash VARCHAR2(100) NOT NULL,
 role VARCHAR2(20) NOT NULL CHECK (role IN ('ADMIN','DISPATCHER','DRIVER'))
);
CREATE TABLE CLIENT (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR2(100) NOT NULL,
 address VARCHAR2(255) NOT NULL,
 phone VARCHAR2(30),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0,1)),
 position MDSYS.SDO_GEOMETRY NOT NULL
);
CREATE TABLE DRIVER (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id NUMBER UNIQUE REFERENCES APP_USER(id),
 name VARCHAR2(100) NOT NULL,
 phone VARCHAR2(30),
 status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL CHECK (status IN ('AVAILABLE','BUSY','OFFLINE')),
 current_position MDSYS.SDO_GEOMETRY NOT NULL,
 position_updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE VEHICLE (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 driver_id NUMBER UNIQUE REFERENCES DRIVER(id),
 plate_number VARCHAR2(30) NOT NULL UNIQUE,
 capacity_kg NUMBER(10,2) NOT NULL CHECK (capacity_kg>0)
);
CREATE TABLE DEPOT (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR2(100) NOT NULL,
 address VARCHAR2(255) NOT NULL,
 position MDSYS.SDO_GEOMETRY NOT NULL
);
CREATE TABLE DELIVERY_ORDER (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_id NUMBER NOT NULL REFERENCES CLIENT(id),
 reference VARCHAR2(50) NOT NULL UNIQUE,
 weight_kg NUMBER(10,2) NOT NULL CHECK (weight_kg>0),
 priority VARCHAR2(10) DEFAULT 'NORMAL' NOT NULL CHECK (priority IN ('LOW','NORMAL','HIGH')),
 status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL CHECK (status IN ('PENDING','ASSIGNED','IN_DELIVERY','DELIVERED','CANCELLED')),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE DELIVERY_ROUTE (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 driver_id NUMBER NOT NULL REFERENCES DRIVER(id),
 depot_id NUMBER NOT NULL REFERENCES DEPOT(id),
 status VARCHAR2(20) DEFAULT 'PLANNED' NOT NULL CHECK (status IN ('PLANNED','IN_PROGRESS','COMPLETED','CANCELLED')),
 algorithm VARCHAR2(20) NOT NULL CHECK (algorithm IN ('NEAREST_NEIGHBOR','TWO_OPT')),
 return_to_depot NUMBER(1) NOT NULL CHECK (return_to_depot IN (0,1)),
 initial_distance_km NUMBER(14,6) NOT NULL CHECK (initial_distance_km>=0),
 total_distance_km NUMBER(14,6) NOT NULL CHECK (total_distance_km>=0),
 depot_longitude NUMBER NOT NULL,
 depot_latitude NUMBER NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
-- Un seul plan actif par livreur, meme en cas de requetes concurrentes.
CREATE UNIQUE INDEX uq_driver_active_route ON DELIVERY_ROUTE (
 CASE WHEN status IN ('PLANNED','IN_PROGRESS') THEN driver_id END
);
CREATE TABLE ROUTE_STOP (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 route_id NUMBER NOT NULL REFERENCES DELIVERY_ROUTE(id),
 order_id NUMBER NOT NULL UNIQUE REFERENCES DELIVERY_ORDER(id),
 stop_order NUMBER NOT NULL CHECK (stop_order>0),
 longitude NUMBER NOT NULL,
 latitude NUMBER NOT NULL,
 segment_distance_km NUMBER(14,6) NOT NULL CHECK (segment_distance_km>=0),
 CONSTRAINT uq_route_rank UNIQUE(route_id,stop_order),
 CONSTRAINT uq_stop_order_pair UNIQUE(id,order_id)
);
CREATE TABLE DELIVERY (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id NUMBER NOT NULL UNIQUE REFERENCES DELIVERY_ORDER(id),
 route_stop_id NUMBER UNIQUE,
 status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL CHECK (status IN ('PENDING','IN_PROGRESS','DELIVERED','FAILED')),
 delivered_at TIMESTAMP,
 CONSTRAINT fk_delivery_stop_order FOREIGN KEY (route_stop_id,order_id) REFERENCES ROUTE_STOP(id,order_id)
);
CREATE INDEX idx_order_client ON DELIVERY_ORDER(client_id);
CREATE INDEX idx_order_status ON DELIVERY_ORDER(status);
CREATE INDEX idx_stop_route ON ROUTE_STOP(route_id);
CREATE INDEX idx_route_depot ON DELIVERY_ROUTE(depot_id);
